<?php

declare(strict_types=1);

use Illuminate\Database\QueryException;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use Src\Shared\Infrastructure\Tenancy\BusinessTransaction;
use Tests\Support\RefreshDatabaseAsOwner;

pest()->use(RefreshDatabaseAsOwner::class);

/** Insert a business with the application role and return its identifier. */
function insertBusiness(string $slug = 'archivum', string $name = 'ArchivumParfums'): string
{
    return (string) DB::table('businesses')->insertGetId([
        'name' => $name,
        'slug' => $slug,
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

/** Insert an account and return its identifier. */
function insertUserAccount(string $email): string
{
    return (string) DB::table('users')->insertGetId([
        'name' => 'Persona de prueba',
        'email' => $email,
        'password' => 'hash',
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

/** Make the next queries reach only the rows of one business, as every request does, before writing its rows. */
function pinBusiness(string $businessId): void
{
    app(BusinessTransaction::class)->scope($businessId);
}

/** Link an account to a business as staff and return the member identifier. */
function insertMember(string $businessId, string $userId, string $role = 'staff'): string
{
    pinBusiness($businessId);

    return (string) DB::table('members')->insertGetId([
        'business_id' => $businessId,
        'user_id' => $userId,
        'role' => $role,
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

/** Give an account a customer record in a business and return its identifier. */
function insertCustomer(string $businessId, string $userId): string
{
    pinBusiness($businessId);

    return (string) DB::table('customers')->insertGetId([
        'business_id' => $businessId,
        'user_id' => $userId,
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

it('gives every table a uuid v7 key generated by the database and timestamptz dates', function (string $table) {
    $columns = collect(Schema::getColumns($table))->keyBy('name')->all();

    expect($columns['id']['type_name'])->toBe('uuid')
        ->and($columns['id']['default'])->toBe('uuidv7()')
        ->and($columns['created_at']['type_name'])->toBe('timestamptz')
        ->and($columns['updated_at']['type_name'])->toBe('timestamptz');
})->with(['businesses', 'members', 'customers']);

it('starts a business with costa rica time, no appointment place and empty settings', function () {
    $business = DB::table('businesses')->where('id', insertBusiness())->sole();

    expect(Str::isUuid($business->id, 7))->toBeTrue()
        ->and($business->timezone)->toBe('America/Costa_Rica')
        ->and($business->location_text)->toBe('')
        ->and($business->logo_path)->toBeNull()
        ->and(json_decode($business->settings, true))->toBe([]);
});

it('stores the settings as jsonb', function () {
    $columns = collect(Schema::getColumns('businesses'))->keyBy('name')->all();

    expect($columns['settings']['type_name'])->toBe('jsonb');
});

it('rejects a repeated slug', function () {
    insertBusiness('archivum');
    insertBusiness('archivum', 'Otra tienda');
})->throws(UniqueConstraintViolationException::class);

it('rejects a slug outside lowercase letters, digits and hyphens', function (string $slug) {
    insertBusiness($slug);
})->with(['Archivum', 'mi tienda', 'mi_tienda', ''])
    ->throws(QueryException::class, 'businesses_slug_check');

it('rejects an empty business name', function () {
    insertBusiness(name: ' ');
})->throws(QueryException::class, 'businesses_name_check');

it('rejects settings that are not an object', function () {
    DB::table('businesses')->where('id', insertBusiness())->update(['settings' => '[2, 5, 10]']);
})->throws(QueryException::class, 'businesses_settings_check');

it('accepts an owner and a staff member who attends appointments', function () {
    $businessId = insertBusiness();

    insertMember($businessId, insertUserAccount('duena@archivum.test'), 'owner');
    DB::table('members')->where('id', insertMember($businessId, insertUserAccount('asesor@archivum.test')))
        ->update(['attends_appointments' => true]);

    expect(DB::table('members')->where('business_id', $businessId)->pluck('role')->sort()->values()->all())
        ->toBe(['owner', 'staff'])
        ->and(DB::table('members')->where('attends_appointments', true)->count())->toBe(1);
});

it('does not let a member attend appointments unless told so', function () {
    $memberId = insertMember(insertBusiness(), insertUserAccount('asesor@archivum.test'));

    expect(DB::table('members')->where('id', $memberId)->sole()->attends_appointments)->toBeFalse();
});

it('rejects an unknown member role', function () {
    insertMember(insertBusiness(), insertUserAccount('admin@archivum.test'), 'admin');
})->throws(QueryException::class, 'members_role_check');

it('rejects a second business for the same staff member', function () {
    $userId = insertUserAccount('asesor@archivum.test');

    insertMember(insertBusiness('archivum'), $userId);
    insertMember(insertBusiness('otra-tienda'), $userId);
})->throws(UniqueConstraintViolationException::class, 'members_user_id_unique');

it('lets one account be a customer of several businesses', function () {
    $userId = insertUserAccount('cliente@archivum.test');

    $businesses = [insertBusiness('archivum'), insertBusiness('otra-tienda')];

    foreach ($businesses as $businessId) {
        insertCustomer($businessId, $userId);
    }

    foreach ($businesses as $businessId) {
        pinBusiness($businessId);

        expect(DB::table('customers')->where('user_id', $userId)->count())->toBe(1);
    }
});

it('rejects a second customer record for the same account in a business', function () {
    $businessId = insertBusiness();
    $userId = insertUserAccount('cliente@archivum.test');

    insertCustomer($businessId, $userId);
    insertCustomer($businessId, $userId);
})->throws(UniqueConstraintViolationException::class, 'customers_business_id_user_id_unique');

it('declares the business and id pair unique so children can use composite foreign keys', function (string $table) {
    $unique = collect(Schema::getIndexes($table))
        ->first(fn (array $index): bool => $index['unique'] && $index['columns'] === ['business_id', 'id']);

    expect($unique)->not->toBeNull();
})->with(['members', 'customers']);

it('keeps the phone of a customer as text for its encrypted value', function () {
    $columns = collect(Schema::getColumns('customers'))->keyBy('name')->all();

    expect($columns['phone']['type_name'])->toBe('text')
        ->and($columns['phone']['nullable'])->toBeTrue();
});

it('rejects members and customers of a business that does not exist', function (string $table) {
    $businessId = (string) Str::uuid7();
    pinBusiness($businessId);

    DB::table($table)->insert([
        'business_id' => $businessId,
        'user_id' => insertUserAccount('persona@archivum.test'),
        'created_at' => now(),
        'updated_at' => now(),
        ...($table === 'members' ? ['role' => 'staff'] : []),
    ]);
})->with(['members', 'customers'])->throws(QueryException::class, 'foreign key');
