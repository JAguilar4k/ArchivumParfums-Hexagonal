<?php

declare(strict_types=1);

use Illuminate\Database\QueryException;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use Tests\Support\RefreshDatabaseAsOwner;
use Tests\Support\Shared\ScopesQueriesToBusiness;

pest()->use(RefreshDatabaseAsOwner::class, ScopesQueriesToBusiness::class);

/** Insert a business where accounts become customers and return its identifier. */
function insertStore(string $slug = 'archivum'): string
{
    return (string) DB::table('businesses')->insertGetId([
        'name' => 'Tienda de prueba',
        'slug' => $slug,
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

/** Insert the account of a customer and return its identifier. */
function insertCustomerAccount(string $email = 'cliente@archivum.test'): string
{
    return (string) DB::table('users')->insertGetId([
        'name' => 'Clienta de prueba',
        'email' => $email,
        'password' => 'hash',
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

/**
 * Give an account a customer record in a business, with that business pinned first, and return its identifier.
 *
 * @param  Closure(?string): void  $scopeQueriesTo
 */
function insertCustomer(Closure $scopeQueriesTo, string $businessId, string $userId): string
{
    $scopeQueriesTo($businessId);

    return (string) DB::table('customers')->insertGetId([
        'business_id' => $businessId,
        'user_id' => $userId,
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

it('identifies customer records with a uuid v7 generated by the database and timestamptz dates', function () {
    $columns = collect(Schema::getColumns('customers'))->keyBy('name')->all();

    expect($columns['id']['type_name'])->toBe('uuid')
        ->and($columns['id']['default'])->toBe('uuidv7()')
        ->and($columns['created_at']['type_name'])->toBe('timestamptz')
        ->and($columns['updated_at']['type_name'])->toBe('timestamptz')
        ->and(Str::isUuid(insertCustomer($this->scopeQueriesTo(...), insertStore(), insertCustomerAccount()), 7))->toBeTrue();
});

it('lets one account be a customer of several businesses', function () {
    $userId = insertCustomerAccount();
    $businesses = [insertStore('archivum'), insertStore('otra-tienda')];

    foreach ($businesses as $businessId) {
        insertCustomer($this->scopeQueriesTo(...), $businessId, $userId);
    }

    foreach ($businesses as $businessId) {
        $this->scopeQueriesTo($businessId);

        expect(DB::table('customers')->where('user_id', $userId)->count())->toBe(1);
    }
});

it('rejects a second customer record for the same account in a business', function () {
    $businessId = insertStore();
    $userId = insertCustomerAccount();

    insertCustomer($this->scopeQueriesTo(...), $businessId, $userId);
    insertCustomer($this->scopeQueriesTo(...), $businessId, $userId);
})->throws(UniqueConstraintViolationException::class, 'customers_business_id_user_id_unique');

it('declares the id and business pair unique so children can use composite foreign keys', function () {
    $unique = collect(Schema::getIndexes('customers'))
        ->first(fn (array $index): bool => $index['unique'] && $index['columns'] === ['id', 'business_id']);

    expect($unique)->not->toBeNull();
});

it('keeps the phone of a customer as text for its encrypted value', function () {
    $columns = collect(Schema::getColumns('customers'))->keyBy('name')->all();

    expect($columns['phone']['type_name'])->toBe('text')
        ->and($columns['phone']['nullable'])->toBeTrue();
});

it('rejects a customer of a business that does not exist', function () {
    insertCustomer($this->scopeQueriesTo(...), (string) Str::uuid7(), insertCustomerAccount());
})->throws(QueryException::class, 'customers_business_id_foreign');

it('deletes the customer records of a business with the business', function () {
    $businessId = insertStore();
    insertCustomer($this->scopeQueriesTo(...), $businessId, insertCustomerAccount());

    DB::table('businesses')->where('id', $businessId)->delete();

    expect(DB::table('customers')->count())->toBe(0)
        ->and(DB::table('users')->count())->toBe(1);
});

it('deletes the customer records of an account with the account', function () {
    $userId = insertCustomerAccount();
    $businesses = [insertStore('archivum'), insertStore('otra-tienda')];

    foreach ($businesses as $businessId) {
        insertCustomer($this->scopeQueriesTo(...), $businessId, $userId);
    }

    DB::table('users')->where('id', $userId)->delete();

    foreach ($businesses as $businessId) {
        $this->scopeQueriesTo($businessId);

        expect(DB::table('customers')->count())->toBe(0);
    }

    expect(DB::table('businesses')->count())->toBe(2);
});
