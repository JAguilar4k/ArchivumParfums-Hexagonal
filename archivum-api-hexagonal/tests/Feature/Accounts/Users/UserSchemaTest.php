<?php

declare(strict_types=1);

use Illuminate\Database\QueryException;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use Tests\Support\RefreshDatabaseAsOwner;

pest()->use(RefreshDatabaseAsOwner::class);

/** Insert an account with the application role and return its identifier. */
function insertAccount(string $email = 'cliente@archivum.test', string $name = 'Clienta de prueba'): string
{
    return (string) DB::table('users')->insertGetId([
        'name' => $name,
        'email' => $email,
        'password' => 'hash',
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

it('identifies accounts with a uuid v7 generated by the database', function () {
    $id = insertAccount();

    expect(Str::isUuid($id, 7))->toBeTrue();
});

it('stores accounts in timestamptz without a business', function () {
    $columns = collect(Schema::getColumns('users'))->keyBy('name')->all();

    expect(array_keys($columns))->not->toContain('business_id')
        ->and($columns['created_at']['type_name'])->toBe('timestamptz')
        ->and($columns['updated_at']['type_name'])->toBe('timestamptz');
});

it('rejects a repeated email whatever its letter case', function () {
    insertAccount('Cliente@Archivum.test');

    insertAccount('cliente@archivum.TEST');
})->throws(UniqueConstraintViolationException::class);

it('rejects an empty name', function () {
    insertAccount(name: '  ');
})->throws(QueryException::class, 'users_name_check');
