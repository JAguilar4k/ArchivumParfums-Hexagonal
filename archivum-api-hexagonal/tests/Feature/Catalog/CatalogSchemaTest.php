it('forces row-level security with the isolation policy on the four catalog tables', function (string $table) {
    $security = DB::selectOne(
        'select relrowsecurity, relforcerowsecurity from pg_class where oid = ?::regclass',
        [$table],
    );
    $policies = DB::select(
        "select policyname, cmd, roles::text as roles, qual, with_check from pg_policies
          where schemaname = 'public' and tablename = ?",
        [$table],
    );

    expect($security->relrowsecurity)->toBeTrue()
        ->and($security->relforcerowsecurity)->toBeTrue()
        ->and($policies)->toEqual([(object) [
            'policyname' => "{$table}_business_isolation",
            'cmd' => 'ALL',
            'roles' => '{public}',
            'qual' => CATALOG_POLICY_EXPRESSION,
            'with_check' => CATALOG_POLICY_EXPRESSION,
        ]]);
})->with(CATALOG_TABLES);

it('shows and changes no catalog row when the transaction has no business', function () {
    $businessId = catalogBusiness('archivum');
    $perfumeId = catalogPerfume($businessId);

    foreach (['perfume_notes', 'perfume_tags', 'perfume_variants'] as $table) {
        DB::table($table)->insert(catalogChildRow($table, $businessId, $perfumeId));
    }

    catalogPin(null);

    foreach (CATALOG_TABLES as $table) {
        expect(DB::table($table)->count())->toBe(0)
            ->and(DB::table($table)->update(['updated_at' => now()]))->toBe(0)
            ->and(DB::table($table)->delete())->toBe(0);
    }

    catalogPin($businessId);

    foreach (CATALOG_TABLES as $table) {
        expect(DB::table($table)->count())->toBe(1);
    }
});

it('shows each business only its own catalog', function () {
    $first = catalogBusiness('archivum');
    $second = catalogBusiness('otra-tienda');

    foreach ([$first, $second] as $businessId) {
        $perfumeId = catalogPerfume($businessId);
        DB::table('perfume_variants')->insert(catalogChildRow('perfume_variants', $businessId, $perfumeId));
    }

    foreach ([$first, $second] as $businessId) {
        catalogPin($businessId);

        expect(DB::table('perfumes')->distinct()->pluck('business_id')->all())->toBe([$businessId])
            ->and(DB::table('perfume_variants')->distinct()->pluck('business_id')->all())->toBe([$businessId]);
    }
});

it('refuses a catalog row for another business', function (string $table) {
    $first = catalogBusiness('archivum');
    $second = catalogBusiness('otra-tienda');
    $perfumeId = catalogPerfume($second);

    catalogPin($first);

    $row = $table === 'perfumes'
        ? ['business_id' => $second, 'brand' => 'Tom Ford', 'name' => 'Intruso', 'created_at' => now(), 'updated_at' => now()]
        : catalogChildRow($table, $second, $perfumeId);

    expectCatalogRejection(
        catalogWriteError(fn () => DB::table($table)->insert($row)),
        '42501',
        'violates row-level security policy',
    );
})->with(CATALOG_TABLES);

it('refuses to move a catalog row to another business and leaves it where it was', function (string $table) {
    $first = catalogBusiness('archivum');
    $second = catalogBusiness('otra-tienda');
    $perfumeId = catalogPerfume($first);

    if ($table !== 'perfumes') {
        DB::table($table)->insert(catalogChildRow($table, $first, $perfumeId));
    }

    expectCatalogRejection(
        catalogWriteError(fn () => DB::table($table)->update(['business_id' => $second])),
        '42501',
        'violates row-level security policy',
    );
    expect(DB::table($table)->distinct()->pluck('business_id')->all())->toBe([$first]);
})->with(CATALOG_TABLES);
