const CATALOG_TABLES = ['perfumes', 'perfume_notes', 'perfume_tags', 'perfume_variants'];

const CATALOG_POLICY_EXPRESSION = "(business_id = (NULLIF(current_setting('app.business_id'::text, true), ''::text))::uuid)";

/** Insert a business and return its identifier. */
function catalogBusiness(string $slug): string
{
    return (string) DB::table('businesses')->insertGetId([
        'name' => 'Tienda de prueba',
        'slug' => $slug,
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

/** Make the next queries reach only the rows of one business, as every request does. */
function catalogPin(?string $businessId): void
{
    app(BusinessTransaction::class)->scope($businessId);
}

/** Insert a perfume in a business, pinned before writing, and return its identifier. */
function catalogPerfume(string $businessId, string $name = 'Oud Wood'): string
{
    catalogPin($businessId);

    return (string) DB::table('perfumes')->insertGetId([
        'business_id' => $businessId,
        'brand' => 'Tom Ford',
        'name' => $name,
        'created_at' => now(),
        'updated_at' => now(),
    ]);
}

/**
 * Row of a table that hangs from a perfume, with the columns that make it valid.
 *
 * @param  array<string, mixed>  $overrides
 * @return array<string, mixed>
 */
function catalogChildRow(string $table, string $businessId, string $perfumeId, array $overrides = []): array
{
    $own = match ($table) {
        'perfume_notes' => ['layer' => 'top', 'note' => 'bergamota'],
        'perfume_tags' => ['kind' => 'time_of_day', 'value' => 'night'],
        'perfume_variants' => ['size_ml' => 100],
        default => throw new InvalidArgumentException("{$table} does not hang from a perfume."),
    };

    return [
        'business_id' => $businessId,
        'perfume_id' => $perfumeId,
        ...$own,
        ...$overrides,
        'created_at' => now(),
        'updated_at' => now(),
    ];
}

/**
 * Run a write inside a savepoint and return the error PostgreSQL answered, or null if it accepted it.
 *
 * @param  Closure(): mixed  $write
 */
function catalogWriteError(Closure $write): ?QueryException
{
    try {
        DB::transaction($write);
    } catch (QueryException $exception) {
        return $exception;
    }

    return null;
}

/** Expect PostgreSQL to have refused a write with this SQLSTATE and the name of the constraint it broke. */
function expectCatalogRejection(?QueryException $error, string $sqlState, string $constraint): void
{
    expect($error?->getCode())->toBe($sqlState)
        ->and($error?->getMessage())->toContain($constraint);
}

