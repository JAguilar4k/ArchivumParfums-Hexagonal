it('rejects the data the checks forbid', function (string $table, array $row, string $constraint) {
    $businessId = catalogBusiness('archivum');
    $perfumeId = catalogPerfume($businessId);

    expectCatalogRejection(
        catalogWriteError(fn () => DB::table($table)->insert(catalogChildRow($table, $businessId, $perfumeId, $row))),
        '23514',
        $constraint,
    );
})->with([
    'a note in an unknown layer' => ['perfume_notes', ['layer' => 'middle'], 'perfume_notes_layer_check'],
    'a tag of an unknown kind' => ['perfume_tags', ['kind' => 'season', 'value' => 'summer'], 'perfume_tags_kind_check'],
    'a moment of the day that does not exist' => ['perfume_tags', ['kind' => 'time_of_day', 'value' => 'noon'], 'perfume_tags_value_check'],
    'a moment of the day in Spanish' => ['perfume_tags', ['kind' => 'time_of_day', 'value' => 'noche'], 'perfume_tags_value_check'],
    'a climate that does not exist' => ['perfume_tags', ['kind' => 'climate', 'value' => 'humid'], 'perfume_tags_value_check'],
    'a climate taken for a moment of the day' => ['perfume_tags', ['kind' => 'climate', 'value' => 'night'], 'perfume_tags_value_check'],
    'a moment of the day taken for a climate' => ['perfume_tags', ['kind' => 'time_of_day', 'value' => 'warm'], 'perfume_tags_value_check'],
    'a presentation of 0 ml' => ['perfume_variants', ['size_ml' => 0], 'perfume_variants_size_ml_check'],
    'a presentation of negative ml' => ['perfume_variants', ['size_ml' => -5], 'perfume_variants_size_ml_check'],
    'a negative sale price' => ['perfume_variants', ['sale_price' => -1], 'perfume_variants_sale_price_check'],
    'a negative manual price' => ['perfume_variants', ['sale_price_override' => -1], 'perfume_variants_sale_price_override_check'],
]);

it('accepts every layer, every moment, every climate and any occasion', function () {
    $businessId = catalogBusiness('archivum');
    $perfumeId = catalogPerfume($businessId);

    foreach (['top', 'heart', 'base'] as $layer) {
        DB::table('perfume_notes')->insert(catalogChildRow('perfume_notes', $businessId, $perfumeId, ['layer' => $layer]));
    }

    $tags = [
        ['time_of_day', 'day'], ['time_of_day', 'afternoon'], ['time_of_day', 'night'],
        ['climate', 'warm'], ['climate', 'temperate'], ['climate', 'cold'],
        ['occasion', 'boda en la playa'],
    ];

    foreach ($tags as [$kind, $value]) {
        DB::table('perfume_tags')->insert(catalogChildRow('perfume_tags', $businessId, $perfumeId, ['kind' => $kind, 'value' => $value]));
    }

    expect(DB::table('perfume_notes')->count())->toBe(3)
        ->and(DB::table('perfume_tags')->count())->toBe(7);
});

it('rejects a repeated key within the same perfume', function (string $table, array $row, string $constraint) {
    $businessId = catalogBusiness('archivum');
    $perfumeId = catalogPerfume($businessId);

    DB::table($table)->insert(catalogChildRow($table, $businessId, $perfumeId, $row));

    expectCatalogRejection(
        catalogWriteError(fn () => DB::table($table)->insert(catalogChildRow($table, $businessId, $perfumeId, $row))),
        '23505',
        $constraint,
    );
})->with([
    'the same size twice' => ['perfume_variants', ['size_ml' => 50], 'perfume_variants_business_id_perfume_id_size_ml_unique'],
    'the same note in the same layer' => ['perfume_notes', ['layer' => 'base', 'note' => 'vainilla'], 'perfume_notes_business_id_perfume_id_layer_note_unique'],
    'the same tag twice' => ['perfume_tags', ['kind' => 'climate', 'value' => 'cold'], 'perfume_tags_business_id_perfume_id_kind_value_unique'],
]);

it('lets the same size, note and tag repeat in another perfume or layer', function () {
    $businessId = catalogBusiness('archivum');
    $first = catalogPerfume($businessId, 'Oud Wood');
    $second = catalogPerfume($businessId, 'Tobacco Vanille');

    foreach ([$first, $second] as $perfumeId) {
        DB::table('perfume_variants')->insert(catalogChildRow('perfume_variants', $businessId, $perfumeId, ['size_ml' => 50]));
        DB::table('perfume_notes')->insert(catalogChildRow('perfume_notes', $businessId, $perfumeId, ['layer' => 'base', 'note' => 'vainilla']));
        DB::table('perfume_tags')->insert(catalogChildRow('perfume_tags', $businessId, $perfumeId, ['kind' => 'climate', 'value' => 'cold']));
    }

    DB::table('perfume_notes')->insert(catalogChildRow('perfume_notes', $businessId, $first, ['layer' => 'top', 'note' => 'vainilla']));

    expect(DB::table('perfume_variants')->count())->toBe(2)
        ->and(DB::table('perfume_notes')->count())->toBe(3)
        ->and(DB::table('perfume_tags')->count())->toBe(2);
});

it('lets two businesses keep the same perfume and size', function () {
    $businesses = [catalogBusiness('archivum'), catalogBusiness('otra-tienda')];

    foreach ($businesses as $businessId) {
        $perfumeId = catalogPerfume($businessId);
        DB::table('perfume_variants')->insert(catalogChildRow('perfume_variants', $businessId, $perfumeId));
    }

    foreach ($businesses as $businessId) {
        catalogPin($businessId);

        expect(DB::table('perfumes')->count())->toBe(1)
            ->and(DB::table('perfume_variants')->count())->toBe(1);
    }
});

