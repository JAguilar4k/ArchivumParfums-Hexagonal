it('identifies every catalog row with a uuid v7 generated by the database and timestamptz dates', function (string $table) {
    $columns = collect(Schema::getColumns($table))->keyBy('name')->all();

    expect($columns['id']['type_name'])->toBe('uuid')
        ->and($columns['id']['default'])->toBe('uuidv7()')
        ->and($columns['business_id']['type_name'])->toBe('uuid')
        ->and($columns['business_id']['nullable'])->toBeFalse()
        ->and($columns['created_at']['type_name'])->toBe('timestamptz')
        ->and($columns['updated_at']['type_name'])->toBe('timestamptz');
})->with(CATALOG_TABLES);

it('generates uuid v7 identifiers for the rows the application does not identify', function () {
    $businessId = catalogBusiness('archivum');
    $perfumeId = catalogPerfume($businessId);
    $rows = [
        'perfume_notes' => (string) DB::table('perfume_notes')->insertGetId(catalogChildRow('perfume_notes', $businessId, $perfumeId)),
        'perfume_tags' => (string) DB::table('perfume_tags')->insertGetId(catalogChildRow('perfume_tags', $businessId, $perfumeId)),
        'perfume_variants' => (string) DB::table('perfume_variants')->insertGetId(catalogChildRow('perfume_variants', $businessId, $perfumeId)),
    ];

    expect(Str::isUuid($perfumeId, 7))->toBeTrue();

    foreach ($rows as $id) {
        expect(Str::isUuid($id, 7))->toBeTrue();
    }
});

it('stores prices as integers and lets a presentation have no price yet', function () {
    $columns = collect(Schema::getColumns('perfume_variants'))->keyBy('name')->all();
    $businessId = catalogBusiness('archivum');
    $perfumeId = catalogPerfume($businessId);

    DB::table('perfume_variants')->insert(catalogChildRow('perfume_variants', $businessId, $perfumeId));

