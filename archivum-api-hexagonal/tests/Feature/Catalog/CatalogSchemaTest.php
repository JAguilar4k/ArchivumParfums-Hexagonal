it('deletes the notes, tags and presentations of a perfume with the perfume', function () {
    $businessId = catalogBusiness('archivum');
    $perfumeId = catalogPerfume($businessId);

    foreach (['perfume_notes', 'perfume_tags', 'perfume_variants'] as $table) {
        DB::table($table)->insert(catalogChildRow($table, $businessId, $perfumeId));
    }

    DB::table('perfumes')->where('id', $perfumeId)->delete();

    expect(DB::table('perfume_notes')->count())->toBe(0)
        ->and(DB::table('perfume_tags')->count())->toBe(0)
        ->and(DB::table('perfume_variants')->count())->toBe(0);
});

it('deletes the catalog of a business with the business', function () {
